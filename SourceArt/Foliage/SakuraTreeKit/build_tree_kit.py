def make_material(name, color, foliage=False):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    mat.diffuse_color = (*linear(color), 1)
    n, links = mat.node_tree.nodes, mat.node_tree.links
    bsdf = n.get('Principled BSDF')
    bsdf.inputs['Roughness'].default_value = .9
    bsdf.inputs['Specular IOR Level'].default_value = .18
    bsdf.inputs['Base Color'].default_value = mat.diffuse_color
    vertex = n.new('ShaderNodeVertexColor'); vertex.layer_name = 'Color'
    vertex.location = (-650, -140)
    mix = n.new('ShaderNodeMixRGB'); mix.blend_type = 'MULTIPLY'
    mix.inputs[0].default_value = 1; mix.inputs[1].default_value = mat.diffuse_color
    mix.location = (-210, 120)
    links.new(vertex.outputs['Color'], mix.inputs[2])
    links.new(mix.outputs[0], bsdf.inputs['Base Color'])
    if foliage:
        tex = n.new('ShaderNodeTexImage'); tex.image = atlas; tex.location = (-650, 200)
        tex.interpolation = 'Linear'
        links.new(tex.outputs['Color'], mix.inputs[1])
        # Same binary mask proposed for Unreal, not alpha-blended transparency.
        cutoff = n.new('ShaderNodeMath'); cutoff.operation = 'GREATER_THAN'
        cutoff.inputs[1].default_value = .4; cutoff.location = (-200, -140)
        links.new(tex.outputs['Alpha'], cutoff.inputs[0]); links.new(cutoff.outputs[0], bsdf.inputs['Alpha'])
        # Small fill keeps isolated thin cards from becoming black at grazing angles.
        links.new(mix.outputs[0], bsdf.inputs['Emission Color'])
        bsdf.inputs['Emission Strength'].default_value = .12
        mat.surface_render_method = 'DITHERED'
        mat.use_backface_culling = False
    return mat

