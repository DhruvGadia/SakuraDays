def tree_spec(kind):
    cfg = VARIANTS[kind]; rng=random.Random(cfg['seed'])
    scale=cfg['scale']; w=cfg['width']; top=cfg['top']; weep=kind=='Weeping'
    paths=[]; groups=[]
    trunk = bezier((0,0,0),(-.23,.12,1.4*scale),(.42,.10,2.7*scale),(.21,.02,3.6*scale),12)
    paths.append((trunk,.29*scale,0))
    # Ground flare is authored as broad short roots, not a floating cylinder.
    for j in range(5):
        a=j*math.tau/5+.15
        root=[Vector((math.cos(a)*.54*scale,math.sin(a)*.54*scale,.055)),Vector((math.cos(a)*.25,math.sin(a)*.25,.18)),Vector((0,0,.55*scale))]
        paths.append((root,.095*scale,1))
    # Unequal central leaders round the canopy and avoid an empty vase-shaped top.
    for j in range(3):
        a=.65+j*2.1
        start=trunk[8+j]
        end=Vector((math.cos(a)*1.2*scale,math.sin(a)*1.2*scale,top+.10-j*.13))
        central=bezier(start,start+Vector((-.35,.20,1.0)),end+Vector((-.35,-.1,-.35)),end,10)
        paths.append((central,.095*scale,0))
        for ix in (6,8,9):groups.append((central[ix],(.82*scale,.72*scale,.43*scale),rng.randint(0,100000)))
    for j in range(cfg['limbs']):
        angle=j*2.399963+.35+rng.uniform(-.14,.14)
        reach=w*rng.uniform(.72,1.03)
        # The upper tiers shorten, preserving an irregular umbrella silhouette.
        tier=j%3
        if tier==2: reach*=.64
        z0=(2.0+tier*.55+rng.uniform(-.18,.18))*scale
        start=trunk[min(10,int(z0/(3.6*scale)*11))].copy()
        direction=Vector((math.cos(angle),math.sin(angle),0))
        endpoint=direction*reach+Vector((.15,-.08,top-1.05+tier*.43+rng.uniform(-.3,.3)))
        tangent=Vector((-direction.y,direction.x,0))
        c1=start+direction*rng.uniform(.45,.9)+tangent*rng.uniform(-.5,.5)+Vector((0,0,rng.uniform(.7,1.25)))
        c2=endpoint-direction*.8+tangent*rng.uniform(-.3,.3)+Vector((0,0,.25 if weep else -.35))
        curve=bezier(start,c1,c2,endpoint,12)
        paths.append((curve,(.15-.014*tier)*scale,0))
        for k in range(5):
            t=.38+k*.135
            base=curve[min(10,int(t*11))]
            side=-1 if k%2 else 1
            a=angle+side*rng.uniform(.37,1.0)
            length=rng.uniform(.65,1.35)*scale
            d=Vector((math.cos(a),math.sin(a),0))
            end=base+d*length+Vector((0,0,.30+rng.random()*.55))
            shoot=bezier(base,base+d*.35+Vector((0,0,.25)),end-d*.25,end,7)
            paths.append((shoot,.037*scale,1))
            for t2 in (.65,1.0):
                p=shoot[int(t2*6)]
                groups.append((p, (.62*scale,.56*scale,.38*scale),rng.randint(0,100000)))
            if weep and k>=1:
                fall=rng.uniform(1.3,2.6)
                bottom=end+d*.40+Vector((0,0,-fall))
                hanging=bezier(end,end+d*.37+Vector((0,0,.15)),bottom+Vector((0,0,.7)),bottom,9)
                paths.append((hanging,.016,2))
                for hi in range(1,9):
                    groups.append((hanging[hi],(.14,.14,.32),rng.randint(0,100000)))
        groups.append((endpoint,(.8*scale,.64*scale,.42*scale),rng.randint(0,100000)))
        if not weep:
            for ix in (7,9):
                groups.append((curve[ix]+Vector((0,0,.30)),(.80*scale,.72*scale,.38*scale),rng.randint(0,100000)))
    return paths,groups,trunk

def create_tree(kind,lod,paths,groups):
    builder=MeshBuilder()
    for points,radius,detail in paths:
        if lod==2 and detail==2:continue
        if lod==2 and detail==1 and radius<.05:continue
        step=1 if lod==0 else 2 if lod==1 else 3
        reduced=points[::step]
        if reduced[-1]!=points[-1]:reduced.append(points[-1])
        builder.tube(reduced,radius,8 if lod==0 else 6 if lod==1 else 5)
    for center,spread,seed in groups:
        rng=random.Random(seed)
        # A retained subset plus increased tuft size keeps distant crown volume.
        hanging=spread[0]<.3
        count=((10,6,3) if hanging else (18,10,5))[lod]
        factor=(1.,1.19,1.48)[lod]
        for i in range(18):
            a=rng.random()*math.tau
            z=rng.uniform(-1,1)
            radial=math.sqrt(1-z*z)
            normal=Vector((radial*math.cos(a),radial*math.sin(a),z*(.15 if hanging else 1)))
            p=Vector(center)+Vector((normal.x*spread[0],normal.y*spread[1],normal.z*spread[2]))*rng.uniform(.25,1)
            size=rng.uniform(.40,.58)*factor if hanging else rng.uniform(.47,.71)*factor
            roll=rng.uniform(-.25,.25) if hanging else rng.random()*math.tau
            tile=rng.randrange(4)
            value=rng.uniform(.88,1.)
            tint=(value, value*.97, min(1,value*1.025))
            if i>=count:continue
            builder.card(p,normal,size,roll,tile,tint,min(1.,max(.4,p.z/7)),hanging)
    name=f'SM_Sakura_{kind}_LOD{lod}'
    builder.vertices=[(x,y,max(0.,z)) for x,y,z in builder.vertices]
    obj=builder.finish(name)
    obj['variant']=kind;obj['lod']=lod;obj['seed']=VARIANTS[kind]['seed']
    obj['foliage']='Original shared atlas, masked two-sided cards, no alpha-blend'
    return obj

def make_collision(obj,trunk):
    result=[]
    for i,(a,b,r1,r2) in enumerate([(trunk[0],trunk[3],.32,.25),(trunk[3],trunk[6],.25,.20),(trunk[6],trunk[9],.20,.14)]):
        # Straight tapered octagonal hulls; tiny gap between segments avoids overlap.
        direction=(b-a).normalized();a=a+direction*(.005 if i else 0);b=b-direction*.005
        u=direction.cross(Vector((0,1,0))).normalized();v=direction.cross(u).normalized()
        verts=[p+r*(math.cos(j*math.tau/8)*u+math.sin(j*math.tau/8)*v) for p,r in ((a,r1),(b,r2)) for j in range(8)]
        faces=[tuple(reversed(range(8))),tuple(range(8,16))]+[(j,(j+1)%8,(j+1)%8+8,j+8) for j in range(8)]
        mesh=bpy.data.meshes.new(f'Collision_{obj.name}_{i}')
        mesh.from_pydata(verts,[],faces);mesh.update()
        hull=bpy.data.objects.new(f'UCX_{obj.name}_{i:02}',mesh);colliders.objects.link(hull)
        hull.hide_render=True;hull.display_type='WIRE';result.append(hull)
    return result

def bounds(obj):
    pts=[v.co for v in obj.data.vertices]
    lo=[min(p[i] for p in pts) for i in range(3)];hi=[max(p[i] for p in pts) for i in range(3)]
    return dict(min=lo,max=hi,dimensions=[hi[i]-lo[i] for i in range(3)])

