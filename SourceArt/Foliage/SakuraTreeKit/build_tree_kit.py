def linear(rgb):
    if isinstance(rgb, str):
        rgb = [int(rgb[i:i+2], 16) / 255 for i in (0, 2, 4)]
    return tuple(v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4 for v in rgb)

def make_atlas():
    """Four original five-petal blossom sprays; analytic masks, no downloaded art."""
    size = 1024
    tile = size // 2
    atlas = np.zeros((size, size, 4), dtype=np.float32)
    atlas[:, :, :3] = (.91, .65, .80)  # pink RGB padding prevents dark fringes
    rng = random.Random(114)
    for tile_index in range(4):
        img = np.zeros((tile, tile, 4), dtype=np.float32)
        img[:, :, :3] = (.91, .65, .80)
        yy, xx = np.mgrid[0:tile, 0:tile].astype(np.float32)
        xx = (xx + .5) / tile
        yy = (yy + .5) / tile
        # Dense central coverage and an irregular flower-defined outside edge.
        points = []
        for j in range(47):
            angle = j * 2.399963 + tile_index * .38
            radius = .30 * math.sqrt(j / 46)
            x = .5 + radius * math.cos(angle) * (1 if tile_index != 3 else .78)
            y = .5 + radius * math.sin(angle)
            points.append((x + rng.uniform(-.028, .028), y + rng.uniform(-.025, .025), rng.uniform(.042, .073)))
        # Far blossoms first, pale foreground blossoms last.
        for j, (cx, cy, r) in enumerate(points):
            rotation = rng.random() * math.tau
            mask = np.zeros((tile, tile), dtype=np.float32)
            for p in range(5):
                a = rotation + p * math.tau / 5
                dx = xx - (cx + math.cos(a) * r * .52)
                dy = yy - (cy + math.sin(a) * r * .52)
                along = dx * math.cos(a) + dy * math.sin(a)
                across = -dx * math.sin(a) + dy * math.cos(a)
                distance = (along / (r * .57)) ** 2 + (across / (r * .42)) ** 2
                petal = np.clip((1.025 - distance) * 27, 0, 1)
                # Tiny sakura notch at the rounded outer tip.
                notch = ((xx - (cx + math.cos(a) * r * 1.05)) ** 2 +
                         (yy - (cy + math.sin(a) * r * 1.05)) ** 2) / (r * .12) ** 2
                petal *= np.clip((notch - .65) * 6, 0, 1)
                mask = np.maximum(mask, petal)
            pale = rng.uniform(0, 1)
            base = np.array([.91 + .065 * pale, .65 + .16 * pale, .79 + .10 * pale])
            radial = np.sqrt((xx - cx) ** 2 + (yy - cy) ** 2) / r
            tint = np.clip(radial * .06, 0, .045)
            color = np.clip(base[None, None, :] + tint[:, :, None], 0, 1)
            # Small muted rose center, deliberately not high-contrast yellow dots.
            center = np.clip((.11 - radial) * 18, 0, .6)
            color = color * (1 - center[:, :, None]) + np.array([.77, .48, .64]) * center[:, :, None]
            img[:, :, :3] = img[:, :, :3] * (1 - mask[:, :, None]) + color * mask[:, :, None]
            img[:, :, 3] = np.maximum(img[:, :, 3], mask)
        ox, oy = (tile_index % 2) * tile, (tile_index // 2) * tile
        atlas[oy:oy+tile, ox:ox+tile] = img
    image = bpy.data.images.new('T_Sakura_Blossom_Atlas', width=size, height=size, alpha=True)
    image.colorspace_settings.name = 'sRGB'
    # This generated byte image saves its sRGB buffer directly; do not double-convert.
    image.pixels.foreach_set(atlas.ravel())
    image.filepath_raw = str(ROOT / 'Textures/T_Sakura_Blossom_Atlas.png')
    image.file_format = 'PNG'
    image.save()
    # Reload file establishes an ordinary external sRGB texture for FBX consumers.
    bpy.data.images.remove(image)
    image = bpy.data.images.load(str(ROOT / 'Textures/T_Sakura_Blossom_Atlas.png'))
    image.name = 'T_Sakura_Blossom_Atlas'
    image.pack()
    return image

